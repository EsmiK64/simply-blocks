import type { BlockInstance } from './types';

function getExpressionPython(block: BlockInstance | null | undefined): string {
    if (!block) {
        return '0';
    }

    const opcode = block.definition.sb3Opcode ?? block.definition.type;
    const f = block.fields;
    const inputs = block.inputs;

    const getVal = (name: string, fallback = '0'): string => {
        if (inputs[name]) {
            return getExpressionPython(inputs[name]);
        }

        if (f[name] !== undefined) {
            return String(f[name]);
        }

        return fallback;
    };

    switch (opcode) {
        case 'operator_add':
            return `(${getVal('NUM1')} + ${getVal('NUM2')})`;
        case 'operator_subtract':
            return `(${getVal('NUM1')} - ${getVal('NUM2')})`;
        case 'operator_multiply':
            return `(${getVal('NUM1')} * ${getVal('NUM2')})`;
        case 'operator_divide':
            return `(${getVal('NUM1')} / ${getVal('NUM2')})`;
        case 'operator_random':
            return `random.randint(${getVal('FROM', '1')}, ${getVal('TO', '10')})`;
        case 'operator_lt':
            return `(${getVal('OPERAND1')} < ${getVal('OPERAND2')})`;
        case 'operator_equals':
            return `(${getVal('OPERAND1')} == ${getVal('OPERAND2')})`;
        case 'operator_gt':
            return `(${getVal('OPERAND1')} > ${getVal('OPERAND2')})`;
        case 'operator_and':
            return `(${getVal('OPERAND1')} and ${getVal('OPERAND2')})`;
        case 'operator_or':
            return `(${getVal('OPERAND1')} or ${getVal('OPERAND2')})`;
        case 'operator_not':
            return `(not ${getVal('OPERAND')})`;
        case 'operator_join':
            return `f"{${getVal('STRING1', '""')}}{${getVal('STRING2', '""')}}"`;
        case 'operator_letter_of':
            return `${getVal('STRING', '""')}[int(${getVal('LETTER', '1')}) - 1]`;
        case 'operator_length':
            return `len(str(${getVal('STRING', '""')}))`;
        case 'data_variable':
            return String(f.VARIABLE ?? 'x');
        case 'sensing_mousex':
            return 'stage.mouse_x';
        case 'sensing_mousey':
            return 'stage.mouse_y';
        case 'sensing_timer':
            return 'stage.timer';
        case 'motion_xposition':
            return 'sprite.x';
        case 'motion_yposition':
            return 'sprite.y';
        case 'motion_direction':
            return 'sprite.direction';
        default:
            return JSON.stringify(f.VALUE ?? f.TEXT ?? f.NUM ?? '0');
    }
}

export function generatePython(blocks: BlockInstance[]): string {
    const lines: string[] = ['# Generated by Simply Blocks', ''];

    const formatBlock = (block: BlockInstance, indent = 0): string[] => {
        const ind = '    '.repeat(indent);
        const opcode = block.definition.sb3Opcode ?? block.definition.type;
        const f = block.fields;
        const res: string[] = [];

        const getVal = (name: string, fallback = '0'): string => {
            if (block.inputs[name]) {
                return getExpressionPython(block.inputs[name]);
            }

            if (f[name] !== undefined) {
                const val = f[name];

                if (typeof val === 'number') {
                    return String(val);
                }

                if (typeof val === 'boolean') {
                    return val ? 'True' : 'False';
                }

                return isNaN(Number(val)) ? JSON.stringify(val) : String(val);
            }

            return fallback;
        };

        switch (opcode) {
            case 'event_whenflagclicked':
                res.push(`${ind}def on_green_flag():`);
                break;
            case 'event_whenkeypressed':
                res.push(`${ind}def on_key_${f.KEY_OPTION ?? 'space'}():`);
                break;
            case 'event_whenthisspriteclicked':
                res.push(`${ind}def on_sprite_clicked():`);
                break;
            case 'motion_movesteps':
                res.push(`${ind}sprite.forward(${getVal('STEPS', '10')})`);
                break;
            case 'motion_turnright':
                res.push(`${ind}sprite.right(${getVal('DEGREES', '15')})`);
                break;
            case 'motion_turnleft':
                res.push(`${ind}sprite.left(${getVal('DEGREES', '15')})`);
                break;
            case 'motion_gotoxy':
                res.push(
                    `${ind}sprite.goto(${getVal('X', '0')}, ${getVal('Y', '0')})`,
                );
                break;
            case 'motion_setx':
                res.push(`${ind}sprite.x = ${getVal('X', '0')}`);
                break;
            case 'motion_sety':
                res.push(`${ind}sprite.y = ${getVal('Y', '0')}`);
                break;
            case 'motion_changexby':
                res.push(`${ind}sprite.x += ${getVal('DX', '10')}`);
                break;
            case 'motion_changeyby':
                res.push(`${ind}sprite.y += ${getVal('DY', '10')}`);
                break;
            case 'looks_sayforsecs':
                res.push(
                    `${ind}sprite.say(${getVal('MESSAGE', '"Hello!"')}, ${getVal('SECS', '2')})`,
                );
                break;
            case 'looks_say':
                res.push(`${ind}sprite.say(${getVal('MESSAGE', '"Hello!"')})`);
                break;
            case 'looks_think':
                res.push(
                    `${ind}sprite.think(${getVal('MESSAGE', '"Hmm..."')})`,
                );
                break;
            case 'looks_show':
                res.push(`${ind}sprite.show()`);
                break;
            case 'looks_hide':
                res.push(`${ind}sprite.hide()`);
                break;
            case 'looks_changesizeby':
                res.push(`${ind}sprite.size += ${getVal('CHANGE', '10')}`);
                break;
            case 'looks_setsizeto':
                res.push(`${ind}sprite.size = ${getVal('SIZE', '100')}`);
                break;
            case 'sound_playuntildone':
                res.push(
                    `${ind}sound.play_until_done(${JSON.stringify(f.SOUND_MENU ?? 'meow')})`,
                );
                break;
            case 'sound_play':
                res.push(
                    `${ind}sound.play(${JSON.stringify(f.SOUND_MENU ?? 'meow')})`,
                );
                break;
            case 'sound_stopallsounds':
                res.push(`${ind}sound.stop_all()`);
                break;
            case 'control_wait':
                res.push(`${ind}time.sleep(${getVal('DURATION', '1')})`);
                break;
            case 'control_repeat':
                res.push(`${ind}for _ in range(${getVal('TIMES', '10')}):`);

                if (block.children.length === 0) {
                    res.push(`${ind}    pass`);
                } else {
                    for (const child of block.children) {
                        res.push(...formatBlock(child, indent + 1));
                    }
                }

                break;
            case 'control_forever':
                res.push(`${ind}while True:`);

                if (block.children.length === 0) {
                    res.push(`${ind}    pass`);
                } else {
                    for (const child of block.children) {
                        res.push(...formatBlock(child, indent + 1));
                    }
                }

                break;
            case 'control_if':
                res.push(`${ind}if ${getVal('CONDITION', 'True')}:`);

                if (block.children.length === 0) {
                    res.push(`${ind}    pass`);
                } else {
                    for (const child of block.children) {
                        res.push(...formatBlock(child, indent + 1));
                    }
                }

                break;
            case 'control_if_else':
                res.push(`${ind}if ${getVal('CONDITION', 'True')}:`);

                if (block.children.length === 0) {
                    res.push(`${ind}    pass`);
                } else {
                    for (const child of block.children) {
                        res.push(...formatBlock(child, indent + 1));
                    }
                }

                res.push(`${ind}else:`);

                if (block.elseChildren.length === 0) {
                    res.push(`${ind}    pass`);
                } else {
                    for (const child of block.elseChildren) {
                        res.push(...formatBlock(child, indent + 1));
                    }
                }

                break;
            case 'control_stop':
                res.push(`${ind}sys.exit()`);
                break;
            case 'data_setvariableto':
                res.push(
                    `${ind}${f.VARIABLE ?? 'my_var'} = ${getVal('VALUE', '0')}`,
                );
                break;
            case 'data_changevariableby':
                res.push(
                    `${ind}${f.VARIABLE ?? 'my_var'} += ${getVal('VALUE', '1')}`,
                );
                break;
            default:
                res.push(`${ind}# ${block.definition.label}`);
                break;
        }

        if (block.next) {
            const nextIndent = block.definition.isHat ? indent + 1 : indent;
            res.push(...formatBlock(block.next, nextIndent));
        }

        return res;
    };

    const childIds = new Set<string>();
    blocks.forEach((b) => {
        if (b.next) {
            childIds.add(b.next.id);
        }

        b.children.forEach((c) => childIds.add(c.id));
        b.elseChildren.forEach((c) => childIds.add(c.id));
        Object.values(b.inputs).forEach((inp) => {
            if (inp) {
                childIds.add(inp.id);
            }
        });
    });

    const topBlocks = blocks.filter((b) => !childIds.has(b.id));

    if (topBlocks.length === 0) {
        return '# Workspace is empty. Drag blocks to assemble your script.';
    }

    topBlocks.forEach((b) => {
        lines.push(...formatBlock(b, 0));
        lines.push('');
    });

    return lines.join('\n');
}
